'use strict';

const assert = require('node:assert/strict');
const { Given, When, Then } = require('@cucumber/cucumber');

Given('un clon del proyecto', function () {
  this.ensureProject();
});

When(/^(Claude Code|OpenCode) busca las skills del proyecto$/, function (agent) {
  this.findSkills(agent);
});

Then('encuentra cada skill de `.agents\\/skills\\/`', function () {
  const { agent, skills } = this.foundSkills;
  const found = new Set(skills.map((skill) => skill.id));
  const expected = this.schemaSkillIds();
  assert.ok(expected.length > 0, 'the project has no schema skills in .agents/skills/');
  assert.deepEqual(
    expected.filter((id) => !found.has(id)),
    [],
    `${agent} does not find these schema skills`
  );
});

Then('cada una aparece una sola vez', function () {
  const { agent, skills } = this.foundSkills;
  const ids = skills.map((skill) => skill.id);
  assert.deepEqual(
    ids.filter((id, i) => ids.indexOf(id) !== i),
    [],
    `${agent} finds these skills more than once`
  );
});

Then('el nombre que declara cada skill coincide con el de su directorio', function () {
  const { agent, skills } = this.foundSkills;
  const mismatched = skills
    .filter((skill) => skill.frontmatter.name !== skill.id)
    .map((skill) => `${skill.source}/${skill.id} declares name '${skill.frontmatter.name}'`);
  assert.deepEqual(mismatched, [], `in ${agent}`);
});

const UNLINKED_SKILL = 'skill-sin-enlazar';

Given('un clon del proyecto con una skill en `.agents\\/skills\\/` que Claude Code no encuentra', function () {
  this.ensureProject().addUnlinkedSchemaSkill(UNLINKED_SKILL);
  this.unlinkedSkill = { id: UNLINKED_SKILL, agent: 'Claude Code' };
});

When('se comprueba la disponibilidad de las skills del proyecto', function () {
  this.checkSkillAvailability();
});

Then('la comprobación falla', function () {
  assert.equal(this.availabilityCheck.failed, true);
});

Then('indica qué skill falta y en qué agente', function () {
  const { id, agent } = this.unlinkedSkill;
  const { problems } = this.availabilityCheck;
  assert.ok(
    problems.some((problem) => problem.includes(`'${id}'`) && problem.startsWith(agent)),
    `no problem names the skill '${id}' and ${agent}: ${JSON.stringify(problems)}`
  );
  // OpenCode reads .agents/skills/ directly, so only Claude Code misses it
  assert.deepEqual(
    problems.filter((problem) => !problem.startsWith(agent)),
    [],
    'only Claude Code should miss the skill'
  );
});

Then('encuentra estas skills de OpenSpec:', function (table) {
  const { agent, skills } = this.foundSkills;
  const found = new Set(skills.map((skill) => skill.id));
  this.expectedWorkflows = table.hashes().map((row) => row.skill);
  assert.deepEqual(
    this.expectedWorkflows.filter((id) => !found.has(id)),
    [],
    `${agent} does not find these OpenSpec workflows`
  );
});

Then('todas corresponden a la versión de OpenSpec fijada por el proyecto', function () {
  const { agent, skills } = this.foundSkills;
  const pinned = this.project.pinnedOpenspecVersion();
  const stale = skills
    .filter((skill) => this.expectedWorkflows.includes(skill.id))
    .filter((skill) => skill.frontmatter.metadata?.generatedBy !== pinned)
    .map((skill) => `${skill.source}/${skill.id}: generatedBy ${skill.frontmatter.metadata?.generatedBy ?? '(none)'}`);
  assert.deepEqual(stale, [], `${agent} finds workflows not generated by the pinned OpenSpec ${pinned}`);
});
